#!/usr/bin/env python3
"""Turn hosts.yaml into ~/.ssh/config and the flat list sshfzf reads.

Both outputs are generated, which is the whole point: the layout this replaces
kept the same sixty-nine names in .ssh/config and .ssh/hosts and maintained both
by hand, and by the time it was looked at they had already drifted apart.

    ./generate.py              write both files
    ./generate.py --tree       print the host tree and exit
    ./generate.py --check      validate hosts.yaml and exit
    ./generate.py --dry-run    print what would be written

Refuses to overwrite an ~/.ssh/config that does not carry the marker below, so a
hand-written config is never clobbered by mistake.
"""

import argparse
import os
import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parent
SOURCE = pathlib.Path(os.environ.get("SSHFZF_HOSTS_YAML") or REPO / "hosts.yaml")
SSH_DIR = pathlib.Path.home() / ".ssh"
CONFIG = SSH_DIR / "config"
HOSTLIST = SSH_DIR / "hosts"

MARKER = "# Generated by sshfzf. Edit hosts.yaml, not this file."


def load():
    with SOURCE.open(encoding="utf-8") as f:
        doc = yaml.safe_load(f) or {}
    defaults = doc.get("defaults") or {}
    hosts = doc.get("hosts") or []
    if not hosts:
        sys.exit(f"{SOURCE.name}: no hosts")
    return defaults, hosts


def validate(hosts):
    """Fail on the mistakes that produce a config ssh accepts but cannot use."""
    problems = []
    names = [h.get("name") for h in hosts]
    for i, h in enumerate(hosts):
        where = h.get("name") or f"hosts[{i}]"
        if not h.get("name"):
            problems.append(f"{where}: no name")
        if not h.get("group"):
            problems.append(f"{where}: no group — it would not appear in the picker")
        if not h.get("hostname"):
            problems.append(f"{where}: no hostname")
        # A ProxyJump naming a host that is not defined here resolves to nothing
        # and the connection fails with a message about the jump host instead.
        jump = h.get("proxy_jump")
        if jump and jump not in names:
            problems.append(f"{where}: proxy_jump '{jump}' is not a host in this file")
    for name in {n for n in names if names.count(n) > 1}:
        problems.append(f"{name}: defined more than once — ssh uses the first and ignores the rest")
    if problems:
        sys.exit("\n".join(problems))


def directive(key):
    """snake_case -> the ssh spelling. Directives are case-insensitive, so this
    needs no table of known options; anything ssh understands passes through."""
    return "".join(part.capitalize() for part in key.split("_"))


def value_of(v):
    """YAML reads `yes` as a bool and Python prints that as True, which ssh does
    not accept -- it wants yes/no."""
    if isinstance(v, bool):
        return "yes" if v else "no"
    return v


def render_config(defaults, hosts):
    out = [MARKER, ""]
    for h in hosts:
        opts = {**defaults, **{k: v for k, v in h.items() if k not in ("name", "group")}}
        out.append(f"#> {h['group']}")
        out.append(f"Host {h['name']}")
        for key, value in opts.items():
            out.append(f"    {directive(key)} {value_of(value)}")
        out.append("")
    return "\n".join(out)


def render_hostlist(hosts):
    """`<group>/<name>` per line, grouped and blank-line separated so the picker
    shows the tree as paths in the order this file declares them."""
    out = [MARKER, ""]
    last = None
    for h in hosts:
        top = h["group"].split("/")[0]
        if last is not None and top != last:
            out.append("")
        out.append(f"{h['group']}/{h['name']}")
        last = top
    return "\n".join(out) + "\n"


def render_tree(hosts):
    tree = {}
    for h in hosts:
        node = tree
        for part in h["group"].split("/"):
            node = node.setdefault(part, {})
        node.setdefault("", []).append(h["name"])

    lines = []

    def walk(node, prefix=""):
        leaves = node.pop("", []) if "" in node else []
        keys = list(node.keys())
        for i, key in enumerate(keys):
            last = i == len(keys) - 1 and not leaves
            lines.append(f"{prefix}{'└── ' if last else '├── '}{key}")
            walk(node[key], prefix + ("    " if last else "│   "))
        for i, leaf in enumerate(leaves):
            last = i == len(leaves) - 1
            lines.append(f"{prefix}{'└── ' if last else '├── '}{leaf}")

    walk(tree)
    return "\n".join(lines)


def write(path, text, mode=0o600):
    if path == CONFIG and path.exists():
        head = path.read_text(encoding="utf-8", errors="replace")[: len(MARKER)]
        if head != MARKER:
            sys.exit(
                f"{path} was not written by this tool and will not be overwritten.\n"
                f"Move it aside first if the hosts in it are already in hosts.yaml."
            )
    SSH_DIR.mkdir(mode=0o700, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    path.chmod(mode)
    print(f"wrote {path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tree", action="store_true", help="print the host tree")
    ap.add_argument("--check", action="store_true", help="validate only")
    ap.add_argument("--dry-run", action="store_true", help="print instead of writing")
    args = ap.parse_args()

    defaults, hosts = load()
    validate(hosts)

    if args.check:
        print(f"{len(hosts)} hosts, no problems")
        return
    if args.tree:
        print(render_tree(hosts))
        return

    config, hostlist = render_config(defaults, hosts), render_hostlist(hosts)
    if args.dry_run:
        print(f"=== {CONFIG}\n{config}\n=== {HOSTLIST}\n{hostlist}", end="")
        return

    write(CONFIG, config)
    write(HOSTLIST, hostlist, mode=0o644)
    print(f"{len(hosts)} hosts")


if __name__ == "__main__":
    main()
